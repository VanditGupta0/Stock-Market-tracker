export function getStockUniverse(): StockAsset[] {
    // Return universe with minor realistic market ticks
    return INITIAL_STOCK_UNIVERSE.map((stock) => {
        // Small random micro-tick (-0.2% to +0.2%)
        const delta = (Math.random() - 0.48) * 0.004;
        const newPrice = Number((stock.price * (1 + delta)).toFixed(2));
        const newPercentChange = Number((stock.percentChange + delta * 100).toFixed(2));
        return {
            ...stock,
            price: newPrice,
            percentChange: newPercentChange,
        };
    });
}
